def build_pdf(path: Path) -> None:
    import pymupdf

    doc = pymupdf.open()
    for title, lines in PAGES:
        page = doc.new_page(width=595, height=842)  # A4
        y = 60
        page.insert_textbox(
            pymupdf.Rect(50, y, 545, y + 40), title,
            fontsize=15, fontname="china-s", align=0,
        )
        y += 48
        body = "\n".join(lines)
        page.insert_textbox(
            pymupdf.Rect(50, y, 545, 800), body,
            fontsize=11, fontname="china-s", lineheight=1.6, align=0,
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(path))
    doc.close()
    print(f"已生成 {path}（{len(PAGES)} 页）")


def main() -> int:
    SAMPLES.mkdir(parents=True, exist_ok=True)
    build_pdf(SAMPLES / "数字图像处理_课件.pdf")
    txt = SAMPLES / "课程补充说明.txt"
    txt.write_text(SUPPLEMENT, encoding="utf-8")
    print(f"已生成 {txt}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
